document.addEventListener('DOMContentLoaded', () => {
    let currentCategory = 'coffee';
    let visibleCount = 0;
    let basePrice = 0;

    let currentSize = 's';
    let selectedAdditives = [];

    const categoryLinks = document.querySelectorAll('.offer__links-li');
    const dishesContainer = document.querySelector('.dishes__card');
    const loadMoreBtn = document.createElement('button');
    loadMoreBtn.classList.add('dishes__load-btn');
    loadMoreBtn.innerHTML = "<svg width=\"24\" height=\"24\" viewBox=\"0 0 24 24\" fill=\"none\" xmlns=\"http://www.w3.org/2000/svg\">\n" +
        "<path d=\"M21.8883 13.5C21.1645 18.3113 17.013 22 12 22C6.47715 22 2 17.5228 2 12C2 6.47715 6.47715 2 12 2C16.1006 2 19.6248 4.46819 21.1679 8\" stroke=\"#403F3D\" stroke-linecap=\"round\" stroke-linejoin=\"round\"/>\n" +
        "<path d=\"M17 8H21.4C21.7314 8 22 7.73137 22 7.4V3\" stroke=\"#403F3D\" stroke-linecap=\"round\" stroke-linejoin=\"round\"/>\n" +
        "</svg>";

    const modal = document.querySelector('#dishModal');

    dishesContainer.after(loadMoreBtn);

    categoryLinks.forEach(link => {
        link.addEventListener('click', () => {
            categoryLinks.forEach(l => l.classList.remove('active'));
            link.classList.add('active');

            currentCategory = link.querySelector('.offer__links-text').textContent.toLowerCase();
            renderProducts(currentCategory);
        });
    });

    loadMoreBtn.addEventListener('click', () => {
        const items = products[currentCategory];
        const remaining = items.slice(visibleCount);
        remaining.forEach(renderCard);
        visibleCount += remaining.length;
        loadMoreBtn.style.display = 'none';
    });

    dishesContainer.addEventListener('click', (e) => {
        const card = e.target.closest('.card');
        if (!card) return;

        const title = card.querySelector('.card__title').textContent.trim();
        const curItem = products[currentCategory].find(v => v.name === title);

        const priceText = card.querySelector('.card__price').textContent.trim();
        basePrice = parseFloat(priceText.replace('$', ''));

        modal.querySelector('.modal__image').src = curItem.img;
        modal.querySelector('.modal__title').textContent = curItem.name;
        modal.querySelector('.modal__desc').textContent = curItem.description;
        const sizes = modal.querySelector('.modal__size-btns');
        const additives = modal.querySelector('.modal__additives-btns');
        const price = modal.querySelector('#modalPrice');
        const modalOverlay = modal.querySelector('.modal__overlay');

        modal.querySelector('.modal__close-btn').addEventListener('click', () => closeModal());

        modalOverlay.addEventListener('click', closeModal);

        function closeModal() {
            modal.classList.remove('active');
            document.body.classList.remove('lock');
            resetPrice()
        }

        function resetPrice() {
            basePrice = 0;
            currentSize = 's';
            selectedAdditives = [];
        }

        function updatePrice() {
            const base = parseFloat(curItem.price);
            const sizeExtra = parseFloat(curItem.sizes[currentSize]['add-price']);
            const additivesExtra = selectedAdditives.length * 0.5;
            const total = base + sizeExtra + additivesExtra;
            price.textContent = `$${total.toFixed(2)}`;
        }

        sizes.innerHTML = Object.entries(curItem.sizes)
            .map(([key, val]) => `
              <button class="modal__size-btn ${key === 's' ? 'active' : ''}" data-size="${key}">
                <span class="modal__size-btn-letter">${key.toUpperCase()}</span> 
                <span class="modal__size-btn-text fs-medium fw-semibold">${val.size}</span>
              </button>
            `).join('');

        sizes.querySelectorAll('.modal__size-btn').forEach(btn => {
            btn.addEventListener('click', () => {
                sizes.querySelectorAll('.modal__size-btn').forEach(b => b.classList.remove('active'));
                btn.classList.add('active');
                currentSize = btn.dataset.size;
                updatePrice();
            });
        });

        additives.innerHTML = curItem.additives
            .map((add, i) => `
              <label class="modal__additive-label">
                <span class="modal__additive-numb">${i + 1}</span>
                <input class="modal__additive-input" type="checkbox" data-index="${i}">
                <span class="modal__additive-text">${add.name}</span>
              </label>
            `).join('');

        additives.querySelectorAll('input').forEach(input => {
            input.addEventListener('change', (e) => {
                const idx = e.target.dataset.index;
                const label = e.target.closest('.modal__additive-label');

                if (e.target.checked) {
                    selectedAdditives.push(idx);
                    label.classList.add('active');
                } else {
                    selectedAdditives = selectedAdditives.filter(i => i !== idx);
                    label.classList.remove('active');
                }

                updatePrice();
            });
        });

        price.textContent = `$${basePrice.toFixed(2)}`;

        modal.classList.add('active');
        document.body.classList.add('lock');
    });

    function renderCard({ name, img, price, description }) {
        const card = document.createElement('div');
        card.className = 'card';
        card.innerHTML = `
          <div class="card__wrap-img">
            <img class="card__img" src="${img}" alt="${name}" loading="lazy">
          </div>
          <div class="card__boxed">
            <div class="card__row">
              <h3 class="card__title heading3">${name}</h3>
              <p class="card__desc fs-medium">${description}</p>
            </div>
            <div class="card__price heading3">$${price}</div>
          </div>
        `;
        dishesContainer.appendChild(card);
    }

    function renderProducts(category) {
        const width = window.innerWidth;
        const perPage = width <= 768 ? 4 : 8;
        const items = products[category];

        dishesContainer.innerHTML = '';
        items.slice(0, perPage).forEach(renderCard);
        visibleCount = perPage;

        loadMoreBtn.style.display = (width <= 768 && items.length > perPage) ? 'block' : 'none';
    }

    renderProducts(currentCategory);

    window.addEventListener('resize', () => renderProducts(currentCategory));
});
